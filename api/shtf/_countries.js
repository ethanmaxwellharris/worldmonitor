const BY_ISO3 = new Map(COUNTRIES.map((c) => [c[0], c]));
const BY_ISO2 = new Map(COUNTRIES.map((c) => [c[1], c]));
const BY_NAME = new Map(COUNTRIES.map((c) => [c[2].toLowerCase(), c[0]]));

export function iso3FromName(name) {
  if (!name) return null;
  const key = String(name).trim().toLowerCase();
  return ALIASES[key] || BY_NAME.get(key) || null;
}
export function iso3FromIso2(iso2) {
  return BY_ISO2.get(String(iso2 || '').toUpperCase())?.[0] || null;
}
export function countryName(iso3) {
  return BY_ISO3.get(iso3)?.[2] || iso3;
}
export function iso2FromIso3(iso3) {
  return BY_ISO3.get(iso3)?.[1] || null;
}
export function isKnownIso3(iso3) {
  return BY_ISO3.has(iso3);
}
